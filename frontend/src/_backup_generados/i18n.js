export function getStatusLabel(status, lang) {
    if (!status)
        return translations[lang].status_on_time;
    switch (status) {
        case 'On Time': return translations[lang].status_on_time;
        case 'Boarding': return translations[lang].status_boarding;
        case 'En Route': return translations[lang].status_en_route;
        case 'Arrived': return translations[lang].status_arrived;
        default: return translations[lang].status_on_time;
    }
}
